import { PaginatedResponseDto } from '@/baseDto/pagination.dto';
import { ToArray } from '@/commonDecorators/array.decorator';
import { GetDepartmentDto } from '@/departmentDto/department.dto';
import { EXAMPLE_USER_ID } from '@/userConst/user.const';
import { GetUserDto } from '@/userDto/user.dto';
import { ApiProperty } from '@nestjs/swagger';

import { Type } from 'class-transformer';
import { IsDate, IsNotEmpty, IsUUID, ValidateNested } from 'class-validator';
import { UUID } from 'crypto';

export class AssignDepartmentsDto {
  @ApiProperty({
    type: String,
    format: 'uuid',
    isArray: true,
    description: 'List of departments IDs to assign to the user',
  })
  @IsUUID(4, { each: true })
  @IsNotEmpty()
  departmentIds: UUID[];

  @ApiProperty({
    type: String,
    format: 'uuid',
    isArray: false,
    description: 'User IDs to which departments will be assigned',
  })
  @IsUUID(4)
  @IsNotEmpty()
  userId: UUID;

  @ApiProperty({
    type: String,
    format: 'uuid',
    isArray: false,
    description: 'User IDs by whom assigned departments to user',
  })
  @IsUUID(4)
  @IsNotEmpty()
  assignedBy: UUID;

  constructor(departmentIds: UUID[], userId: UUID, assignedBy: UUID) {
    this.departmentIds = departmentIds;
    this.userId = userId;
    this.assignedBy = assignedBy;
  }
}

