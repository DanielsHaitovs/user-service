import { PaginatedResponseDto } from '@/baseDto/pagination.dto';
import { ToArray } from '@/commonDecorators/array.decorator';
import { GetRoleResponseDto } from '@/roleDto/role.dto';
import { EXAMPLE_USER_ID } from '@/userConst/user.const';
import { GetUserDto } from '@/userDto/user.dto';
import { ApiProperty } from '@nestjs/swagger';

import { Type } from 'class-transformer';
import { IsDate, IsNotEmpty, IsUUID, ValidateNested } from 'class-validator';
import { UUID } from 'crypto';

export class AssignRolesDto {
  @ApiProperty({
    type: String,
    format: 'uuid',
    isArray: true,
    description: 'List of role IDs to assign to the user',
  })
  @IsUUID(4, { each: true })
  @IsNotEmpty()
  roleIds: UUID[];

  @ApiProperty({
    type: String,
    format: 'uuid',
    isArray: false,
    description: 'User IDs to which role will be assigned',
  })
  @IsUUID(4)
  @IsNotEmpty()
  userId: UUID;

  @ApiProperty({
    type: String,
    format: 'uuid',
    isArray: false,
    description: 'User IDs to who assigned roles to user',
  })
  @IsUUID(4)
  @IsNotEmpty()
  assignedBy: UUID;

  constructor(roleIds: UUID[], userId: UUID, assignedBy: UUID) {
    this.roleIds = roleIds;
    this.userId = userId;
    this.assignedBy = assignedBy;
  }
}

